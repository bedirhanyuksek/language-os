import { expect, test } from '@playwright/test'
import { catalog } from './catalog-fixture'
import { restoreLegacy } from './legacy-profile'

test('opens the roadmap from navigation and shows the current lesson, estimates and collapsible levels', async ({ page }, testInfo) => {
  if (testInfo.project.name === 'mobile') await page.setViewportSize({ width: 390, height: 844 })
  await page.clock.setFixedTime(new Date('2026-11-20T10:00:00.000Z'))
  await page.goto('/')
  await restoreLegacy(page, catalog.es, { minutes: 15, days: [1, 3, 5] })
  const navigation = page.getByRole('navigation', { name: 'Ana menü' })
  await navigation.getByRole('button', { name: 'Yol haritam', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Yol haritam', exact: true })).toBeVisible()
  await expect(navigation.getByRole('button', { name: 'Yol haritam' })).toHaveAttribute('aria-current', 'page')
  await expect(page.getByText('Buradasın', { exact: true })).toBeVisible()
  await expect(page.locator('[aria-current="step"]')).toContainText(catalog.es.unit.lessons[0].title)
  await expect(page.getByText('Sıradaki ders', { exact: true })).toHaveCount(1)
  await expect(page.getByRole('heading', { name: 'Bu hafta', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Önümüzdeki 4 hafta', exact: true })).toBeVisible()
  await expect(page.getByText('Günde 15 dk × haftada 3 seçili çalışma günü = 45 dk/hafta.')).toBeVisible()
  const currentLevel = page.locator('.roadmap-level').filter({ has: page.locator('[aria-current="step"]') })
  await currentLevel.locator(':scope > summary').click()
  await expect(page.getByText('Buradasın', { exact: true })).toBeHidden()
  await currentLevel.locator(':scope > summary').click()
  await expect(page.getByText('Buradasın', { exact: true })).toBeVisible()
  const unpublished = page.locator('.roadmap-level').filter({ has: page.locator('.roadmap-band', { hasText: 'C2' }) })
  await expect(unpublished.locator(':scope > summary')).toContainText('henüz yayımlanmadı')
  await unpublished.locator(':scope > summary').click()
  await expect(unpublished.getByText('Bu seviyede ders henüz yayımlanmadı.', { exact: true })).toBeVisible()
  await page.getByText('Tahmini ders sırası', { exact: true }).first().click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.screenshot({ path: testInfo.outputPath('roadmap.png'), fullPage: true })
  await navigation.getByRole('button', { name: 'Plan', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Yol haritam', exact: true })).toHaveCount(0)
})
